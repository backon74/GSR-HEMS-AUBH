"""Generated artefacts: demo_day.json, firmware/replay_table.h, HARDWARE_CONTRACT.md, magnus.h (8, 7.8)."""
import json
import math

import config
from logic import runner


def magnus_dew(temp_c, rh_pct, a=None, b=None):
    a = config.MAGNUS_A if a is None else a
    b = config.MAGNUS_B if b is None else b
    g = math.log(max(rh_pct, 1e-6) / 100.0) + a * temp_c / (b + temp_c)
    return b * g / (a - g)


def loop_seconds():
    n_peak = len(config.PEAK_HOURS)
    return (24 - n_peak) * config.SECONDS_PER_SIM_HOUR + n_peak * config.SECONDS_PER_PEAK_HOUR


def _day_score(g, scenario):
    modes = list(g['actual_mode'])
    run = best = 0
    for m in modes:
        run = run + 1 if m == 'peak_reduce' else 0
        best = max(best, run)
    score = 0
    score += 2 if 'pre_cool' in modes else 0
    score += 2 if best >= 3 else 0
    score += 1 if 'normal' in modes else 0
    score += 3 if (scenario and 'comfort_override' in modes) else 0
    return score + 0.01 * len(set(modes))


def select_demo_day(fdf):
    """Pick the day (and scenario) that shows every mode. Nominal first; scenario only when needed."""
    cands = []
    for sname in (None, 'heatwave'):
        sc = config.SCENARIOS[sname] if sname else None
        s, plans, params = runner.build_schedule(fdf, scenario=sc)
        for date, g in s.groupby('date'):
            full = ({'pre_cool', 'peak_reduce', 'normal'} <= set(g['actual_mode']))
            has_ov = 'comfort_override' in set(g['actual_mode'])
            cands.append((_day_score(g, sc) + (5 if (full and has_ov) else 0), date, sname, g))
    cands.sort(key=lambda x: (-x[0], x[1]))
    score, date, sname, g = cands[0]
    cols = ['hour', 'planned_mode', 'actual_mode', 'override_reason', 'indoor_temp_est_c', 'indoor_rise_c',
            'predicted_indoor_next_c', 'kwh_baseline', 'kwh_optimized', 'kwh_recovery', 'fan_pwm', 'led',
            'tariff_period', 'temp', 'humidity', 'dew_point', 'reason', 'scenario']
    rows = g.sort_values('hour')[cols].to_dict('records')
    for r in rows:
        r['hour_ms'] = 1000 * (config.SECONDS_PER_PEAK_HOUR if r['hour'] in config.PEAK_HOURS
                               else config.SECONDS_PER_SIM_HOUR)
    return {'date': date, 'scenario': config.SCENARIOS[sname] if sname else None,
            'scenario_label': 'SCENARIO: ' + sname if sname else None, 'score': round(score, 2),
            'data_source': g['data_source'].iloc[0], 'loop_seconds': loop_seconds(), 'rows': rows}


def write_demo_day(demo, path='results/demo_day.json'):
    with open(path, 'w') as f:
        json.dump(demo, f, indent=2, default=lambda o: o.item() if hasattr(o, 'item') else str(o))


def _arr(name, ctype, vals):
    return f"static const {ctype} {name}[24] = {{{', '.join(str(v) for v in vals)}}};"


def replay_table_text(demo):
    rows = demo['rows']
    mode_idx = {m: i for i, m in enumerate(config.MODES)}
    lines = [
        '// GENERATED by evaluation/exports.py from results/demo_day.json. Do not edit by hand.',
        f"// date {demo['date']}  scenario {demo['scenario']['name'] if demo['scenario'] else 'none'}  "
        f"data_source {demo['data_source']}",
        '#pragma once',
        '#include <stdint.h>',
        f"// mode: {', '.join(f'{i}={config.MODE_TOKEN[m]}' for m, i in mode_idx.items())}",
        '#define REPLAY_HOURS 24',
        _arr('REPLAY_MODE', 'uint8_t', [mode_idx[r['actual_mode']] for r in rows]),
        _arr('REPLAY_FAN_PCT', 'uint8_t', [r['fan_pwm'] for r in rows]),
        _arr('REPLAY_LED_GPIO', 'uint8_t', [config.LED_GPIO[r['led']] for r in rows]),
        _arr('REPLAY_INDOOR_X10', 'int16_t', [int(round(r['indoor_temp_est_c'] * 10)) for r in rows]),
        _arr('REPLAY_KWH_BASE_X100', 'uint16_t', [int(round(r['kwh_baseline'] * 100)) for r in rows]),
        _arr('REPLAY_KWH_OPT_X100', 'uint16_t', [int(round(r['kwh_optimized'] * 100)) for r in rows]),
        _arr('REPLAY_HOUR_MS', 'uint16_t', [r['hour_ms'] for r in rows]),
    ]
    return '\n'.join(lines) + '\n'


def magnus_header_text():
    return ('// GENERATED from config.py. Same constants as logic/exports magnus_dew().\n#pragma once\n'
            '#include <math.h>\n'
            f'static const float MAGNUS_A = {config.MAGNUS_A}f;\nstatic const float MAGNUS_B = {config.MAGNUS_B}f;\n'
            'static inline float magnus_dew(float t, float rh) {\n'
            '  float g = logf(rh / 100.0f) + MAGNUS_A * t / (MAGNUS_B + t);\n'
            '  return MAGNUS_B * g / (MAGNUS_A - g);\n}\n')


